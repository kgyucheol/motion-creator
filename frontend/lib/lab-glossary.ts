/** The explanation for a label, ignoring trailing notes and punctuation. */
export function termFor(label: string): Term | undefined {
  const text = label.replace(/\s+/g, ' ').trim();
  return GLOSSARY[text] ?? GLOSSARY[text.replace(/\s*\(.*\)$/, '')];
}
